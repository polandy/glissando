/** Never calls `onWave`; a placeholder for tests that do not care about the clip's sound. */
export const neverReportingReadClipPeaks: ReadClipPeaks = () => new Promise(() => {});

/** Resolves with the first call's arguments, so a test can await it instead of racing the effect. */
export function fakeReadClipPeaks(): {
  readClipPeaks: ReadClipPeaks;
  calledWith: Promise<{ blob: Blob; sourceMs: number; signal: AbortSignal }>;
} {
  let resolveCalledWith: (call: { blob: Blob; sourceMs: number; signal: AbortSignal }) => void;
  const calledWith = new Promise<{ blob: Blob; sourceMs: number; signal: AbortSignal }>(
    (resolve) => {
      resolveCalledWith = resolve;
    },
  );
  const readClipPeaks: ReadClipPeaks = (blob, sourceMs, signal) => {
    resolveCalledWith({ blob, sourceMs, signal });
    return new Promise(() => {});
  };
  return { readClipPeaks, calledWith };
}

/** Resolves with the first state of the pass that `matches`. */
export function stateOf(
  pass: FocusPass,
  matches: (state: FocusPassState) => boolean,
): Promise<void> {
  return new Promise((resolve) => {
    const stop = pass.subscribe((state) => {
      if (matches(state)) {
        queueMicrotask(stop);
        resolve();
      }
    });
  });
}

let destroy = () => {};

export function unmountRoute(): void {
  destroy();
}

export async function mountRoute(
  pictureId: string,
  readClipPeaks: ReadClipPeaks = neverReportingReadClipPeaks,
  stored: StoredSlideshow = SHOW,
  /** Built from this route's own store, so a test's pass reads and writes the same records. */
  createFocusPass: (store: MemoryLibraryStore) => Pick<FocusPass, "lookAgain"> = () => ({
    lookAgain: () => {},
  }),
) {
  const store = new MemoryLibraryStore();
  for (const picture of stored.pictures) {
    await store.putPicture(picture.id, { display: new Blob([]), thumbnail: new Blob([]) });
  }
  await store.putVideo(CLIP_VIDEO.mediaId, CLIP_BLOB);
  await store.saveSlideshow(stored);
  const focusPass = createFocusPass(store);
  const errors: unknown[] = [];
  const editor = new SlideshowEditor(stored, {
    store,
    toaster: new Toaster(new FakeScheduler()),
    newId: () => "claim-1",
    now: () => new Date("2026-10-08T12:00:00Z"),
    onError: (error) => errors.push(error),
    onGone: () => {},
    onRefused: () => {},
    removedText: () => "Bild entfernt",
    addedText: () => "Bilder hinzugefügt",
    undoLabel: () => "Rückgängig",
    lastPictureText: () => "Das letzte Bild bleibt.",
    everyPictureText: () => "Mindestens ein Bild bleibt.",
    motionAutomaticText: () => "Bewegung wieder automatisch",
    durationAutomaticText: () => "Bilddauer wieder automatisch",
    transitionAutomaticText: () => "Übergang wieder automatisch",
    slideshowTransitionResetText: () => "Übergänge wieder auf Überblenden",
    portraitPicturesResetText: () => "Hochformatbilder wieder automatisch",
    lookResetText: () => "Look entfernt",
    moodResetText: () => "Stimmung ausgeschaltet",
    moodNowCustomText: () => "Keine Stimmung ist an",
    songRemovedText: () => "Song entfernt",
    shuffledText: () => "",
    random: () => 0,
    automaticTitle: () => "Juli 2025",
    locale: () => "de-DE",
    focusOf: () => undefined,
  });
  let backs = 0;
  let resolveLogged: (error: unknown) => void = () => {};
  const logged = new Promise<unknown>((resolve) => {
    resolveLogged = resolve;
  });
  const props = reactiveProps({
    store,
    stored,
    focus: NO_FOCUS_KNOWN,
    focusPass,
    passPaused: false,
    beatPass: beatPassFindingNone(store),
    loudnessPass: loudnessPassFindingNone(store),
    editor,
    pictureId,
    saving: false,
    onBack: () => (backs += 1),
    onOpen: () => {},
    onError: (error: unknown) => errors.push(error),
    log: (error: unknown) => {
      errors.push(error);
      resolveLogged(error);
    },
    readClipPeaks,
  });
  const mounted = mountWithTranslator(PictureEditorRoute, props);
  destroy = mounted.destroy;
  return { target: mounted.target, backs: () => backs, store, editor, errors, logged, props };
}
