/** The picture "c"'s clip; generated bytes stand in for a video file, never a real one. */
const CLIP_VIDEO = { mediaId: "video-1", sourceMs: 60_000, startMs: 0, endMs: 10_000 };
const CLIP_BLOB = new Blob(["clip bytes"], { type: "video/mp4" });

const SHOW: StoredSlideshow = {
  id: "show",
  title: "Juli 2025",
  createdAt: "2025-07-02T00:00:00Z",
  pictures: [
    ...["a", "b"].map((id) => ({
      id,
      capturedAt: "2025-07-01T10:00:00Z",
      width: 100,
      height: 100,
      fileName: `${id}.jpg`,
      colours: { veil: "#404040", accent: "#C0C0C0" },
    })),
    {
      id: "c",
      capturedAt: "2025-07-01T10:00:00Z",
      width: 100,
      height: 100,
      fileName: "c.mp4",
      colours: { veil: "#404040", accent: "#C0C0C0" },
      video: CLIP_VIDEO,
    },
  ],
  secondsPerPicture: 5,
  songs: [],
};

/** Never calls `onWave`; a placeholder for tests that do not care about the clip's sound. */
const neverReportingReadClipPeaks: ReadClipPeaks = () => new Promise(() => {});

/** Resolves with the first call's arguments, so a test can await it instead of racing the effect. */
function fakeReadClipPeaks(): {
  readClipPeaks: ReadClipPeaks;
  calledWith: Promise<{ blob: Blob; sourceMs: number; signal: AbortSignal }>;
} {
  let resolveCalledWith: (call: { blob: Blob; sourceMs: number; signal: AbortSignal }) => void;
  const calledWith = new Promise<{ blob: Blob; sourceMs: number; signal: AbortSignal }>(
    (resolve) => {
      resolveCalledWith = resolve;
    },
  );
  const readClipPeaks: ReadClipPeaks = (blob, sourceMs, signal) => {
    resolveCalledWith({ blob, sourceMs, signal });
    return new Promise(() => {});
  };
  return { readClipPeaks, calledWith };
}

let destroy = () => {};
afterEach(() => destroy());

async function mountRoute(
  pictureId: string,
  readClipPeaks: ReadClipPeaks = neverReportingReadClipPeaks,
) {
  const store = new MemoryLibraryStore();
  for (const picture of SHOW.pictures) {
    await store.putPicture(picture.id, { display: new Blob([]), thumbnail: new Blob([]) });
  }
  await store.putVideo(CLIP_VIDEO.mediaId, CLIP_BLOB);
  await store.saveSlideshow(SHOW);
  const errors: unknown[] = [];
  const editor = new SlideshowEditor(SHOW, {
    store,
    toaster: new Toaster(new FakeScheduler()),
    newId: () => "claim-1",
    now: () => new Date("2026-10-08T12:00:00Z"),
    onError: (error) => errors.push(error),
    onGone: () => {},
    onRefused: () => {},
    removedText: () => "Bild entfernt",
    addedText: () => "Bilder hinzugefügt",
    undoLabel: () => "Rückgängig",
    lastPictureText: () => "Das letzte Bild bleibt.",
    everyPictureText: () => "Mindestens ein Bild bleibt.",
    motionAutomaticText: () => "Bewegung wieder automatisch",
    durationAutomaticText: () => "Dauer wieder automatisch",
    transitionAutomaticText: () => "Übergang wieder automatisch",
    slideshowTransitionResetText: () => "Übergänge wieder auf Überblenden",
    portraitPicturesResetText: () => "Hochformatbilder wieder automatisch",
    songRemovedText: () => "Song entfernt",
    shuffledText: () => "",
    random: () => 0,
    automaticTitle: () => "Juli 2025",
    locale: () => "de-DE",
    focusOf: () => undefined,
  });
  let backs = 0;
  let resolveLogged: (error: unknown) => void = () => {};
  const logged = new Promise<unknown>((resolve) => {
    resolveLogged = resolve;
  });
  const props = reactiveProps({
    store,
    stored: SHOW,
    focus: NO_FOCUS_KNOWN,
    beatPass: beatPassFindingNone(store),
    editor,
    pictureId,
    saving: false,
    onBack: () => (backs += 1),
    onOpen: () => {},
    onError: (error: unknown) => errors.push(error),
    log: (error: unknown) => {
      errors.push(error);
      resolveLogged(error);
    },
    readClipPeaks,
  });
  const mounted = mountWithTranslator(PictureEditorRoute, props);
  destroy = mounted.destroy;
  return { target: mounted.target, backs: () => backs, store, editor, errors, logged, props };
}

const FACE: PictureFocus = {
  kind: "subject",
  box: { x: 0.4, y: 0.2, width: 0.2, height: 0.3 },
  foundBy: "face",
};

/** Resolves with the first state of the pass that `matches`. */
function stateOf(pass: FocusPass, matches: (state: FocusPassState) => boolean): Promise<void> {
  return new Promise((resolve) => {
    const stop = pass.subscribe((state) => {
      if (matches(state)) {
        queueMicrotask(stop);
        resolve();
      }
    });
  });
}

describe("the picture editor route", () => {
  it("shows a picture of the slideshow and stays", async () => {
    const { target, backs } = await mountRoute("b");

    expect(target.querySelector(".pic")).not.toBeNull();
    expect(backs()).toBe(0);
  });

  it("goes back to the slideshow when the picture is no longer in it", async () => {
    const { target, backs } = await mountRoute("gone");

    expect(target.querySelector(".pic")).toBeNull();
    expect(backs()).toBe(1);
  });

  it("stores the caption typed for the picture, normalised", async () => {
    const { target, store, editor, errors } = await mountRoute("b");
    const field = target.querySelector<HTMLInputElement>('input[type="text"]');
    if (field === null) {
      throw new Error("the caption field is missing");
    }

    field.value = "Abends  am Steg";
    field.dispatchEvent(new Event("input", { bubbles: true }));
    await editor.settled();

    const stored = await store.getSlideshow("show");
    expect(stored.pictures[1]?.caption).toBe("Abends am Steg");
    expect(errors).toEqual([]);
  });

  it("marks the focus the background pass finds while the picture is open", async () => {
    const { target, store, props } = await mountRoute("b");
    const detector = new FakeFocusDetector(() => FACE);
    const held = detector.holdNext();
    const pass = new FocusPass({ store, detector, log: () => {}, reportError: () => {} });
    // As the slideshow route does: what the pass finds joins the focus the editor shows.
    pass.subscribe((state) => (props.focus = picturesFocus(new Map(), state)));
    const searching = stateOf(pass, (state) => state.searching.has("b"));

    pass.start();
    await searching;
    flushSync();
    const marker = () => target.querySelector('[role="img"][aria-label="Fokus: Gesicht erkannt"]');
    expect(target.querySelector('[role="status"]')?.textContent?.trim()).toBe(
      "Fokus wird gesucht …",
    );
    expect(marker()).toBeNull();

    held.release();
    await pass.settled();
    flushSync();

    expect(marker()).not.toBeNull();
    expect(target.querySelector('[role="status"]')).toBeNull();
  });

  it("shows the next picture's known focus at once when ‹/› moves on to it", async () => {
    const { target, props } = await mountRoute("a");
    const found = { found: new Map([["b", FACE]]), searching: new Set<string>() };
    props.focus = found;
    flushSync();

    props.pictureId = "b";
    flushSync();

    const marker = target.querySelector('[role="img"][aria-label="Fokus: Gesicht erkannt"]');
    expect(marker).not.toBeNull();
    expect(marker?.getAnimations()).toEqual([]);
  });

  it("reads the stored clip's blob and its source length", async () => {
    const { readClipPeaks, calledWith } = fakeReadClipPeaks();
    await mountRoute("c", readClipPeaks);

    const call = await calledWith;

    expect(await call.blob.text()).toBe(await CLIP_BLOB.text());
    expect(call.sourceMs).toBe(CLIP_VIDEO.sourceMs);
  });

  it("says the clip's sound cannot be read, and logs why, when the reader fails", async () => {
    const failure = new Error("no audio decoder in this browser");
    const { target, logged } = await mountRoute("c", () => Promise.reject(failure));

    expect(await logged).toBe(failure);
    flushSync();

    expect(target.textContent).toContain("Ton kann hier nicht gelesen werden");
  });

  it("aborts the reader's signal when the clip editor closes", async () => {
    const { readClipPeaks, calledWith } = fakeReadClipPeaks();
    await mountRoute("c", readClipPeaks);
    const call = await calledWith;
    expect(call.signal.aborted).toBe(false);

    destroy();

    expect(call.signal.aborted).toBe(true);
  });
});
